/**
 * @param {object} opts
 * @param {string} opts.host  bind address (default 127.0.0.1 — use 0.0.0.0 behind a reverse proxy)
 * @param {number} opts.port
 * @param {string|null} [opts.commit]  short git sha for initialize serverInfo and GET /version.
 *                                     Omit to read this checkout; null to report commit: null.
 * @param {object|null} [opts.gate]  charge gate (createChargeGate) — null serves free
 * @param {string|null} [opts.paymentNote]  how calls are paid when another rail (NEAR) gates them;
 *                                   shown on the landing page and in /llms.txt. No pay page is served for it.
 * @param {object|null} [opts.rates]  NEAR-rail rates service (src/near/rates.mjs): serves GET /rates
 *                                   (?refresh=1 forces a refetch, rate-limited by the service)
 * @param {Array} [opts.toolInfo]  registry.tools — per-tool editorUrl/rawText/x402/card for the landing page and /graph/:name.json
 * @param {object} [opts.costs]  registry.costs — live last-observed-cost records, shown on the landing cards
 * @param {string|null} [opts.outDir]  when set, /out/<file> serves generated media from it
 * @param {number} [opts.progressMs]  heartbeat interval on streamed tools/call responses
 * @param {number} [opts.maxStreams]  cap on concurrently-held event streams (tools/call holds +
 *                                    /x402/watch subscribers). At the cap, new tools/call requests
 *                                    are answered as plain JSON (the pre-hold-open behaviour) and
 *                                    new watch subscriptions get a 503 so the pay page falls back to
 *                                    polling — a held-connection backstop, far above real concurrency.
 * @returns {Promise<http.Server>}
 */
export async function serveHttp({
  host = "127.0.0.1",
  port,
  name,
  version,
  commit,
  listTools,
  callTool,
  instructions,
  gate = null,
  paymentNote = null,
  rates = null,
  toolInfo = [],
  costs = {},
  outDir = null,
  publicBase,
  progressMs = 10_000,
  maxStreams = 4096,
  log = (...a) => console.error(...a),
}) {
  const sha = commit === undefined ? gitShortSha() : (commit || null);
  const publicOrigin = new URL(publicBase || `http://${host}:${port}`).origin;
  const dispatch = createDispatcher({ name, version, commit: sha, listTools, callTool, instructions, log });
  const graphByName = new Map(toolInfo.filter((t) => t.rawText).map((t) => [t.name, t.rawText]));

  // Every held event stream (a streaming tools/call, a /x402/watch subscriber)
  // rides the gate's ONE shared payment watcher — no per-connection polling — so
  // a parked connection costs a socket, a heartbeat timer, and a waiter slot,
  // nothing that scales with the chain. This counter is only a socket backstop.
  let activeStreams = 0;

  const server = http.createServer(async (req, res) => {
    // Routing needs only the path. An untrusted Host header must not throw
    // before the request's error boundary (or influence URL parsing).
    const send = (code, body, type = "application/json") => {
      res.writeHead(code, { "Content-Type": type, "Access-Control-Allow-Origin": "*" });
      res.end(body);
    };

    try {
      const url = new URL(req.url, "http://localhost");
      // Check before preflight or dispatch. Do not derive trust from Host or
      // forwarded headers supplied by the request being authorized.
      if (url.pathname === "/mcp" && req.headers.origin !== undefined && req.headers.origin !== publicOrigin) {
        return send(403, JSON.stringify({ error: "Origin is not allowed" }));
      }
      if (req.method === "OPTIONS") {
        res.writeHead(204, {
          "Access-Control-Allow-Origin": "*",
          "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
          "Access-Control-Allow-Headers": "Content-Type, Mcp-Session-Id, Mcp-Protocol-Version",
        });
        return res.end();
      }

      if (url.pathname === "/mcp") {
        if (req.method === "GET") return send(405, JSON.stringify({ error: "no server-initiated stream — POST JSON-RPC messages here" }));
        if (req.method !== "POST") return send(405, JSON.stringify({ error: "POST only" }));
        if (!/^application\/json\b/.test(req.headers["content-type"] || "")) {
          return send(415, JSON.stringify({ error: "Content-Type must be application/json" }));
        }
        const chunks = [];
        let len = 0;
        for await (const c of req) {
          len += c.length;
          if (len > MAX_BODY) return send(413, JSON.stringify({ error: "body too large" }));
          chunks.push(c);
        }
        let msg;
        try { msg = JSON.parse(Buffer.concat(chunks).toString("utf8")); }
        catch { return send(400, JSON.stringify({ jsonrpc: "2.0", id: null, error: { code: -32700, message: "parse error" } })); }

        /*
         * tools/call from an SSE-capable client streams: heartbeats every
         * progressMs — MCP progress notifications when the client sent a
         * progressToken (clients reset their tool timeout on these), plain SSE
         * comments otherwise (keeps proxies from idling the socket) — then the
         * final response. A generation or payment wait can take minutes; a
         * silent held-open POST is exactly what client timeouts kill.
         */
        const isCall = msg && typeof msg === "object" && msg.method === "tools/call" && msg.id !== null && msg.id !== undefined;
        // At the held-connection cap we don't refuse the call — we drop to the
        // plain-JSON path below, which still answers correctly (a paid call just
        // returns its quote to relay instead of holding open). Graceful, not a 503.
        if (isCall && activeStreams < maxStreams && /\btext\/event-stream\b/i.test(req.headers.accept || "")) {
          const progressToken = msg.params && msg.params._meta ? msg.params._meta.progressToken : undefined;
          res.writeHead(200, {
            "Content-Type": "text/event-stream",
            "Cache-Control": "no-cache",
            "Access-Control-Allow-Origin": "*",
          });
          activeStreams++;
          const event = (obj) => { if (!res.writableEnded && !res.destroyed) res.write(`event: message\ndata: ${JSON.stringify(obj)}\n\n`); };
          const t0 = Date.now();
          let ticks = 0;
          const emitProgress = (message) => {
            if (progressToken === undefined) return false; // no progress channel on this call
            event({ jsonrpc: "2.0", method: "notifications/progress", params: { progressToken, progress: ++ticks, message } });
            return true;
          };
          /*
           * ctx rides through the dispatcher to the (gated) tool:
           *   report(s)   — set the status the next heartbeat repeats
           *   announce(s) — also push that line as a progress update immediately,
           *                 not just at the next heartbeat (no-op returning false
           *                 when the call carries no progressToken). Used for
           *                 mid-run status the caller should see without waiting.
           */
          const ctx = {
            streaming: true,
            status: "working",
            report(s) { this.status = s; },
            announce(s) { this.status = s; return emitProgress(s); },
          };
          const beat = setInterval(() => {
            const line = `${ctx.status} (${Math.round((Date.now() - t0) / 1000)}s elapsed)`;
            if (!emitProgress(line) && !res.writableEnded && !res.destroyed) {
              res.write(`: ${line}\n\n`); // SSE comment — connection warmth without protocol noise
            }
          }, progressMs);
          if (beat.unref) beat.unref();
          let released = false;
          const release = () => {
            if (released) return;
            released = true;
            clearInterval(beat);
            activeStreams--;
            res.off("close", release);
          };
          res.once("close", release);
          try {
            const response = await dispatch(msg, ctx);
            if (response) event(response);
          } finally {
            release();
            if (!res.writableEnded && !res.destroyed) res.end();
          }
          return;
        }

        const response = await dispatch(msg);
        if (!response) { res.writeHead(202, { "Access-Control-Allow-Origin": "*" }); return res.end(); }
        return send(200, JSON.stringify(response));
      }

      if (req.method !== "GET" && req.method !== "HEAD") return send(405, JSON.stringify({ error: "method not allowed" }));

      if (url.pathname === "/") {
        return send(200, landingHtml({ name, version, listTools, publicBase, charged: !!gate, toolInfo, costs, paymentNote }), "text/html; charset=utf-8");
      }

      if (url.pathname === "/llms.txt") {
        return send(200, llmsTxt({ name, version, listTools, publicBase, charged: !!gate, toolInfo, paymentNote }), "text/plain; charset=utf-8");
      }

      if (url.pathname === "/rates" && rates) {
        const force = ["1", "true", "yes"].includes(url.searchParams.get("refresh") || "");
        res.writeHead(200, { "Content-Type": "application/json", "Access-Control-Allow-Origin": "*", "Cache-Control": "no-store" });
        return res.end(JSON.stringify(await rates.view({ refresh: force }), null, 2));
      }

      if (url.pathname === "/version") {
        return send(200, JSON.stringify({ name, version, commit: sha }));
      }

      if (ASSETS[url.pathname]) {
        const path = join(ASSET_DIR, basename(url.pathname));
        if (!existsSync(path)) return send(404, JSON.stringify({ error: "not found" }));
        res.writeHead(200, {
          "Content-Type": ASSETS[url.pathname],
          "Access-Control-Allow-Origin": "*",
          "Cache-Control": "public, max-age=86400",
        });
        if (req.method === "HEAD") return res.end();
        return createReadStream(path).on("error", () => res.destroy()).pipe(res);
      }

      const graphMatch = url.pathname.match(/^\/graph\/([^/]+)\.json$/);
      if (graphMatch) {
        const raw = graphByName.get(decodeURIComponent(graphMatch[1]));
        if (!raw) return send(404, JSON.stringify({ error: "not found" }));
        return send(200, raw, "application/json; charset=utf-8");
      }

      const payMatch = url.pathname.match(/^\/pay\/([^/]+)$/);
      if (payMatch && gate) {
        const q = gate.quote(decodeURIComponent(payMatch[1]));
        if (!q) return send(404, htmlPage("Not found", "<h1>Unknown or expired payment</h1><p class=\"muted\">Ask your agent for a fresh quote.</p>"), "text/html; charset=utf-8");
        return send(200, payPageHtml(q), "text/html; charset=utf-8");
      }

      const statusMatch = url.pathname.match(/^\/x402\/status\/([^/]+)$/);
      if (statusMatch && gate) {
        const id = decodeURIComponent(statusMatch[1]);
        if (url.searchParams.get("wait")) {
          const stop = new AbortController();
          const leave = () => stop.abort();
          res.once("close", leave);
          try { await gate.waitForPayment(id, 25_000, { signal: stop.signal }); }
          finally { res.off("close", leave); }
          if (res.destroyed) return;
        }
        const q = gate.quote(id);
        // Terminal quotes carry done + next (agent instructions for the result stream).
        return send(200, JSON.stringify(q
          ? { status: q.status, amountRaw: q.amountRaw, expiresAt: q.expiresAt, ...(q.done ? { done: true, next: q.next } : {}) }
          : { status: "unknown", done: true, next: "Unknown payment id — call the tool again without _payment_id for a fresh quote." }));
      }

      /*
       * SSE payment watch: one `status` event per state change. When the quote
       * settles (paid / expired / …) the FINAL frame includes done:true and a
       * `next` imperative telling the agent how to open the result stream
       * (tools/call with _payment_id) — then the connection closes. Without that,
       * a subscriber sees bare "paid" and a loading gap with no path forward.
       * The pay page only reads `.status` (extra fields are harmless). Rides the
       * gate's shared waiter list; at the held-connection cap it 503s so the
       * caller falls back to polling.
       */
      const watchMatch = url.pathname.match(/^\/x402\/watch\/([^/]+)$/);
      if (watchMatch && gate) {
        const id = decodeURIComponent(watchMatch[1]);
        if (activeStreams >= maxStreams) return send(503, JSON.stringify({ error: "too many open streams — poll /x402/status instead" }));
        res.writeHead(200, {
          "Content-Type": "text/event-stream",
          "Cache-Control": "no-cache",
          "Access-Control-Allow-Origin": "*",
        });
        activeStreams++;
        let alive = true;
        const stop = new AbortController();
        const sse = (ev, obj) => { if (alive && !res.writableEnded && !res.destroyed) res.write(`event: ${ev}\ndata: ${JSON.stringify(obj)}\n\n`); };
        // Frame shape shared with /x402/status — pending is lean; terminal carries
        // done + next so the agent knows how to access the result stream after close.
        const frame = (q) => {
          if (!q) return { status: "unknown", done: true, next: "Unknown payment id — call the tool again without _payment_id for a fresh quote." };
          const f = { status: q.status, amountRaw: q.amountRaw, expiresAt: q.expiresAt };
          if (q.done) { f.done = true; if (q.next) f.next = q.next; }
          return f;
        };
        const ping = setInterval(() => { if (alive && !res.writableEnded && !res.destroyed) res.write(`: ping\n\n`); }, progressMs);
        if (ping.unref) ping.unref();
        const leave = () => {
          if (!alive) return;
          alive = false;
          stop.abort();
          clearInterval(ping);
          activeStreams--;
          res.off("close", leave);
        };
        res.once("close", leave);
        try {
          let q = gate.quote(id);
          sse("status", frame(q));
          // Hold the stream open across state changes until the quote settles or
          // the client leaves. Each wait resolves on the shared watcher firing
          // (paid/expired) or its own 25s ceiling — a re-poll that also lets a
          // dropped connection be noticed and cleaned up.
          const deadline = Date.now() + 20 * 60 * 1000; // never outlive a quote (15m TTL + slack)
          while (alive && q && q.status === "pending" && Date.now() < deadline) {
            await gate.waitForPayment(id, 25_000, { signal: stop.signal });
            if (!alive) break;
            q = gate.quote(id);
            if (q) sse("status", frame(q));
            // On settle the final frame already carried done+next; the loop exits
            // and finally{} closes the stream — that close IS the acknowledgment.
          }
        } finally {
          leave();
          if (!res.writableEnded && !res.destroyed) res.end();
        }
        return;
      }

      const outMatch = url.pathname.match(/^\/out\/([^/]+)$/);
      if (outMatch && outDir) {
        const file = decodeURIComponent(outMatch[1]);
        // This directory also contains the gate state, ledger and staging files.
        // Only generated media may cross the public artifact boundary.
        if (file !== basename(file) || !MEDIA_EXTS.has(extname(file).slice(1).toLowerCase())) {
          return send(404, JSON.stringify({ error: "not found" }));
        }
        const path = join(outDir, file);
        let handle;
        try {
          // Check and stream the same descriptor; a symlink must never turn a
          // media-looking name into a read of bookkeeping or another directory.
          handle = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
          if (!(await handle.stat()).isFile()) {
            await handle.close();
            return send(404, JSON.stringify({ error: "not found" }));
          }
        } catch (e) {
          await handle?.close();
          if (["ENOENT", "ENOTDIR", "ELOOP"].includes(e.code)) return send(404, JSON.stringify({ error: "not found" }));
          throw e;
        }
        const ext = file.split(".").pop().toLowerCase();
        res.writeHead(200, {
          "Content-Type": OUT_MIME[ext] || "application/octet-stream",
          "Access-Control-Allow-Origin": "*",
          "Cache-Control": "private, max-age=86400",
        });
        if (req.method === "HEAD") { await handle.close(); return res.end(); }
        // pipeline releases the file descriptor when the client leaves early.
        pipeline(handle.createReadStream(), res, () => {});
        return;
      }

      return send(404, JSON.stringify({ error: "not found" }));
    } catch (e) {
      log(`nanoodle-mcp: http error on ${req.method} ${req.url}: ${(e && e.stack) || e}`);
      if (!res.headersSent) send(500, JSON.stringify({ error: "internal error" }));
      else res.destroy();
    }
  });

  await new Promise((resolve, reject) => {
    server.once("error", reject);
    server.listen(port, host, resolve);
  });
  return server;
}
