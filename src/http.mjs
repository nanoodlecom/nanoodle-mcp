/** "auto-dub" → "Auto dub": the card title for humans; the exact tool id rides beside it. */
const toolTitle = (name) => {
  const s = String(name).replace(/-/g, " ");
  return s.charAt(0).toUpperCase() + s.slice(1);
};

/**
 * One-line "register this server" commands for the clients that ship an
 * `mcp add --transport http` CLI. Same endpoint, same flag shape — only the
 * binary name changes. Landing page defaults to Claude; a toggle flips to Grok.
 */
const connectCmds = (publicBase) => ({
  claude: `claude mcp add --transport http noodles ${publicBase}/mcp`,
  grok: `grok mcp add --transport http noodles ${publicBase}/mcp`,
});

/**
 * How many of the served workflows actually route the markup to an author.
 *
 * The 20% is the author's cut ONLY when a graph carries `"x402": {"author": "nano_…"}`.
 * With no such field the gate keeps it (src/gate.mjs settle()), so any copy that says
 * "the 20% goes to the workflow author" full stop is false on a server whose graphs
 * name nobody — which is every graph in awesome-noodles today. Count first, then write.
 */
function authorCount(toolInfo) {
  return toolInfo.filter((t) => t && t.x402 && typeof t.x402.author === "string" && t.x402.author.trim()).length;
}


function workflowExampleHtml(name) {
  const example = workflowExample(name);
  if (!example) return "";
  return `<div class="example"><p><strong>${example.skill ? "Made with this skill: " : ""}${esc(example.title)}</strong></p>` +
    (example.preview ? `<a href="${esc(example.play)}"><img src="${esc(example.preview)}" alt="${esc(example.alt || example.title)}" loading="lazy"></a>` : "") +
    `<p class="muted">${esc(example.description)}</p>` +
    `<p><a href="${esc(example.play)}">See sample</a>` +
    (example.skill ? ` · <a href="${esc(example.skill)}">give your agent the skill</a>` : "") + `</p></div>`;
}

function sampleCall(name) {
  return { jsonrpc: "2.0", id: 1, method: "tools/call", params: { name, arguments: {} } };
}

function workflowSampleHtml(name, sample) {
  if (!sample) return "";
  return `<details class="sample"><summary>Try the included sample</summary>` +
    `<p><strong>${esc(sample.label)}:</strong> ${esc(sample.text)}</p>` +
    `<p class="muted">Send this MCP call after connecting. It uses the saved inputs and requests a paid generation.</p>` +
    `<pre>${esc(JSON.stringify(sampleCall(name), null, 2))}</pre></details>`;
}

