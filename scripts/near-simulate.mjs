#!/usr/bin/env node
/**
 * Offline end-to-end simulation of a NEAR-paid nanoodle-mcp server.
 *
 *   node scripts/near-simulate.mjs        (npm run simulate:near)
 *
 * Starts the real server (bin/nanoodle-mcp.mjs --serve --near-merchant …) as a
 * child process against two local stand-ins: a NEAR chain that speaks the
 * JSON-RPC wire format of public testnet RPC, and NanoGPT (catalogs, chat,
 * image). Then it plays an agent over MCP-over-HTTP and prints exactly what the
 * agent sees at each step: discover tools, read the authoring guide, price a
 * custom graph, get a quote, pay it with one transfer, run with the receipt,
 * replay, and every refusal and recovery path, including killing the server
 * mid-run and mid-refund. It ends with both balances reconciled.
 *
 * Needs no network, no keys and no funds: the merchant key is a throwaway
 * generated in this process. Exits non-zero on any failed expectation.
 */
import { spawn } from "node:child_process";
import { createServer } from "node:net";
import { mkdtemp, mkdir, writeFile, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createFakeChain, throwawayNearKey, nanoGptMock, WORKED_GRAPH, GAS_YOCTO } from "../tests/fixtures/near-fake-chain.mjs";
import { formatYoctoAsNear, parseNearToYocto } from "../src/near/amount.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const BIN = join(ROOT, "bin", "nanoodle-mcp.mjs");
const MERCHANT = "merchant.testnet";
const PAYER = "payer.testnet";
/** docs/near-payments.md#worked-example: the charge does not depend on the random dust. */
const DOC = { charged: 3102197802197802197803n, refundAtDust137: 5276802197802197802197n, depositAtDust137: 8379000000000000000000n };

export const freePort = () => new Promise((resolve, reject) => {
  const s = createServer();
  s.once("error", reject);
  s.listen(0, "127.0.0.1", () => { const { port } = s.address(); s.close(() => resolve(port)); });
});
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** Start bin/nanoodle-mcp.mjs in NEAR mode; resolves once it serves. */
export async function startServer({ graphsDir, outDir, chainUrl, nanoUrl, secretKey, port, log = () => {} }) {
  const env = {
    PATH: process.env.PATH,
    HOME: outDir,
    NANOGPT_API_KEY: "sim-api-key",
    NANOGPT_BASE_URL: nanoUrl,
    NEAR_PRIVATE_KEY: secretKey, // a throwaway generated by this script
  };
  const child = spawn(process.execPath, [
    BIN, "--graphs", graphsDir, "--out", outDir, "--serve", `127.0.0.1:${port}`, "--public-url", `http://127.0.0.1:${port}`,
    "--near-merchant", MERCHANT, "--near-network", "testnet", "--near-rpc", chainUrl, "--near-usd", "3.64",
  ], { env, stdio: ["ignore", "ignore", "pipe"] });
  let stderr = "";
  child.stderr.setEncoding("utf8");
  child.stderr.on("data", (c) => { stderr += c; });
  const t0 = Date.now();
  while (!/MCP over HTTP on/.test(stderr)) {
    if (child.exitCode !== null) throw new Error("server exited during startup:\n" + stderr);
    if (Date.now() - t0 > 20_000) { child.kill("SIGKILL"); throw new Error("server did not start:\n" + stderr); }
    await sleep(25);
  }
  log(stderr.split("\n").filter((l) => /NEAR|run_noodle|MCP over HTTP|interrupted|settled after/.test(l)).map((l) => "  [server] " + l.replace(/^nanoodle-mcp:\s*/, "")).join("\n"));
  return {
    child,
    get stderr() { return stderr; },
    kill: () => new Promise((r) => { child.once("exit", r); child.kill("SIGKILL"); }),
  };
}

/** A minimal MCP client over streamable HTTP (plain JSON responses). */
export function mcpClient(base) {
  let id = 0;
  async function rpc(method, params) {
    const res = await fetch(base + "/mcp", {
      method: "POST",
      headers: { "content-type": "application/json", accept: "application/json" },
      body: JSON.stringify({ jsonrpc: "2.0", id: ++id, method, params }),
    });
    const msg = await res.json();
    return msg;
  }
  return {
    rpc,
    initialize: () => rpc("initialize", { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "near-simulate", version: "1" } }),
    list: async () => (await rpc("tools/list")).result.tools,
    call: async (name, args) => {
      const m = await rpc("tools/call", { name, arguments: args });
      if (m.error) return { rpcError: m.error };
      return m.result;
    },
  };
}

/**
 * Run the whole simulation. `print` receives the transcript. Returns
 * { failures, checks, facts } — the e2e test imports this.
 */
export async function runSimulation({ print = console.log } = {}) {
  const failures = [];
  let checks = 0;
  const expect = (ok, what) => {
    checks++;
    if (ok) print(`  ✓ ${what}`);
    else { failures.push(what); print(`  ✗ ${what}`); }
  };
  const step = (title) => print(`\n=== ${title} ===`);
  const agentSees = (r) => {
    if (!r) return;
    if (r.rpcError) { print(`  agent sees a JSON-RPC error ${r.rpcError.code}: ${r.rpcError.message}`); return; }
    const txt = (r.content || []).filter((c) => c.type === "text").map((c) => c.text).join("\n");
    print((r.isError ? "  agent sees (isError):\n" : "  agent sees:\n") + txt.split("\n").map((l) => "  | " + l).join("\n"));
  };
  const facts = {};

  const work = await mkdtemp(join(tmpdir(), "near-sim-"));
  const graphsDir = join(work, "noodles");
  const outDir = join(work, "out");
  await mkdir(graphsDir, { recursive: true });
  await writeFile(join(graphsDir, "idea-poster.json"), JSON.stringify(WORKED_GRAPH, null, 2));

  const chain = createFakeChain();
  const key = await throwawayNearKey();
  chain.addAccount(MERCHANT, parseNearToYocto("10"), key.publicKey);
  chain.addAccount(PAYER, parseNearToYocto("5"));
  const nano = nanoGptMock();
  await chain.listen();
  await nano.listen();
  const port = await freePort();
  const base = `http://127.0.0.1:${port}`;
  const startOpts = { graphsDir, outDir, chainUrl: chain.url, nanoUrl: nano.url, secretKey: key.secretKey, port, log: print };
  const start0 = { merchant: chain.balance(MERCHANT), payer: chain.balance(PAYER) };
  const ledger = []; // every payment this script makes, for the reconciliation
  const stateQuote = async (id) => JSON.parse(await readFile(join(outDir, "near-state.json"), "utf8")).quotes[id];

  print("nanoodle-mcp NEAR simulation — offline: local NEAR chain stand-in, local NanoGPT stand-in, throwaway merchant key.");
  print(`merchant ${MERCHANT} starts with ${formatYoctoAsNear(start0.merchant)} NEAR, payer ${PAYER} with ${formatYoctoAsNear(start0.payer)} NEAR.`);

  let server;
  try {
    step("1. Start the server in NEAR mode (testnet, static rate 1 NEAR = $3.64)");
    server = await startServer(startOpts);
    const mcp = mcpClient(base);
    const init = await mcp.initialize();
    print("  initialize → instructions:\n  | " + init.result.instructions);
    expect(/paid per call in native NEAR on testnet/.test(init.result.instructions), "the server tells agents it is paid in NEAR");

    step("2. Discover tools");
    const tools = await mcp.list();
    for (const t of tools) print(`  - ${t.name}: ${t.description.slice(0, 160)}${t.description.length > 160 ? "…" : ""}`);
    const names = tools.map((t) => t.name).sort();
    expect(JSON.stringify(names) === JSON.stringify(["idea-poster", "noodle_guide", "price_noodle", "run_noodle"]), "run_noodle, price_noodle, noodle_guide and the saved graph are offered");
    expect(!!tools.find((t) => t.name === "run_noodle").inputSchema.properties._payment_tx, "paid tools take _payment_id/_payment_tx/_payment_sender");

    step("3. Learn how to write a graph: noodle_guide { kind: \"image\", limit: 3 }");
    const guide = await mcp.call("noodle_guide", { kind: "image", limit: 3 });
    print(guide.content[0].text.split("\n").filter((l, i) => i < 4 || /^Priced models|^- image /.test(l)).map((l) => "  | " + l).join("\n"));
    expect(!guide.isError && guide.structuredContent.models.length === 1, "noodle_guide lists the priced image model");

    const args = { graph: WORKED_GRAPH, inputs: { Idea: "a lighthouse at dawn" } };
    step("4. Price a custom graph for free: price_noodle { graph: text → llm → image, inputs: { Idea } }");
    const price = await mcp.call("price_noodle", args);
    agentSees(price);
    expect(!price.isError && price.structuredContent.pricing.deposit.usd === "0.03", "price_noodle: $0.03 deposit, as in the worked example");
    expect(price.structuredContent.near.likelyChargeNear === "0.003172", "price_noodle: likely charge 0.003172 NEAR");

    step("5. Ask to run it without paying: run_noodle { graph, inputs } → a quote");
    const runsBefore = nano.runs();
    const quote = await mcp.call("run_noodle", args);
    agentSees(quote);
    const pay = quote.structuredContent.payment;
    const deposit = BigInt(pay.amountYocto);
    expect(!quote.isError && pay.status === "payment_required" && pay.payTo === MERCHANT, "the quote names the merchant and the network");
    expect(deposit >= 8243n * 10n ** 18n && deposit <= 9241n * 10n ** 18n && deposit % 10n ** 18n === 0n, `deposit ${pay.amountNear} NEAR = 0.008242 + 1..999 µNEAR of dust`);
    expect(nano.runs() === runsBefore, "quoting ran nothing");

    step("6. The agent's wallet sends ONE transfer of exactly the quoted amount");
    const tx = chain.transfer(PAYER, MERCHANT, deposit);
    ledger.push({ kind: "deposit", yocto: deposit });
    print(`  wallet: near tokens ${PAYER} send-near ${MERCHANT} '${pay.amountNear} NEAR' … → tx ${tx}`);

    step("7. Call again with the payment: run_noodle { graph, inputs, _payment_id, _payment_tx, _payment_sender }");
    const paid = await mcp.call("run_noodle", { ...args, _payment_id: pay.paymentId, _payment_tx: tx, _payment_sender: PAYER });
    agentSees(paid);
    const rc = paid.structuredContent && paid.structuredContent.receipt;
    expect(!paid.isError && rc && rc.outcome === "succeeded", "the run succeeded and carries a receipt");
    expect(rc && BigInt(rc.charged.yocto) === DOC.charged, `charged ${rc && rc.charged.yocto} yocto = the worked example's ${DOC.charged}`);
    expect(rc && BigInt(rc.refund.yocto) === deposit - DOC.charged, `refund ${rc && rc.refund.yocto} yocto = deposit − charged`);
    expect(DOC.depositAtDust137 - DOC.charged === DOC.refundAtDust137, `with the doc's dust (137 steps) the refund is exactly ${DOC.refundAtDust137}`);
    expect(rc && rc.refund.status === "sent" && chain.txs.has(rc.refund.txHash), "the refund transfer is on chain");
    expect(rc && rc.actualCost.usd === "0.00941" && rc.serviceFee.usd === "0.001882" && rc.charged.usd === "0.011292", "receipt: $0.00941 actual + $0.001882 fee = $0.011292");
    expect(nano.runs() === runsBefore + 1, "the workflow ran exactly once");
    if (rc) ledger.push({ kind: "refund", yocto: BigInt(rc.refund.yocto) });
    facts.receipt = rc;

    step("8. Replay the paying call");
    const runs8 = nano.runs(), sends8 = chain.sendTxCount;
    const replay = await mcp.call("run_noodle", { ...args, _payment_id: pay.paymentId, _payment_tx: tx, _payment_sender: PAYER });
    print("  agent sees the same result and receipt again.");
    expect(JSON.stringify(replay.structuredContent.receipt) === JSON.stringify(rc), "replay returns the stored receipt");
    expect(nano.runs() === runs8 && chain.sendTxCount === sends8, "replay: no new run, no new refund");

    step("9. Reuse the same transaction for a new quote");
    const args2 = { graph: WORKED_GRAPH, inputs: { Idea: "a second idea" } };
    const q2 = await mcp.call("run_noodle", args2);
    const reuse = await mcp.call("run_noodle", { ...args2, _payment_id: q2.structuredContent.payment.paymentId, _payment_tx: tx, _payment_sender: PAYER });
    agentSees(reuse);
    expect(reuse.isError && /already used/.test(reuse.content[0].text), "a consumed transaction is refused");

    step("10. Refusals before any quote: an endpoint node, and a model the catalog cannot price");
    const unsafe = await mcp.call("run_noodle", { graph: { nodes: [{ id: "n1", type: "endpoint", name: "Internal", fields: { url: "" } }], links: [] } });
    agentSees(unsafe);
    expect(unsafe.isError && unsafe.structuredContent.refusals[0].code === "NODE_NOT_ALLOWED", "an endpoint node is refused, nothing quoted");
    const unpriced = await mcp.call("run_noodle", { graph: { nodes: [{ id: "n1", type: "llm", name: "Writer", fields: { model: "someone/unlisted-model", prompt: "hi" } }], links: [] } });
    agentSees(unpriced);
    expect(unpriced.isError && /someone\/unlisted-model/.test(unpriced.content[0].text), "an unpriceable model is refused and named");

    step("11. Underpay a quote by 0.0000005 NEAR");
    const args3 = { graph: WORKED_GRAPH, inputs: { Idea: "underpaid" } };
    const q3 = (await mcp.call("run_noodle", args3)).structuredContent.payment;
    // Half a dust step: every quote is a whole number of 0.000001 NEAR steps, so this
    // amount can never be the exact amount of some other open quote.
    const short = BigInt(q3.amountYocto) - 5n * 10n ** 17n;
    const tx3 = chain.transfer(PAYER, MERCHANT, short);
    ledger.push({ kind: "deposit", yocto: short });
    const runs11 = nano.runs();
    const under = await mcp.call("run_noodle", { ...args3, _payment_id: q3.paymentId, _payment_tx: tx3, _payment_sender: PAYER });
    agentSees(under);
    const rc11 = under.structuredContent.receipt;
    expect(under.isError && rc11.outcome === "wrong_amount" && BigInt(rc11.refund.yocto) === short && rc11.refund.status === "sent", "wrong amount: nothing runs, everything is refunded");
    expect(nano.runs() === runs11, "underpaid: no run");
    ledger.push({ kind: "refund", yocto: short });

    step("12. Pay a quote after it expired (block time after expiresAt)");
    const args4 = { graph: WORKED_GRAPH, inputs: { Idea: "too late" } };
    const q4 = (await mcp.call("run_noodle", args4)).structuredContent.payment;
    const tx4 = chain.transfer(PAYER, MERCHANT, BigInt(q4.amountYocto), { blockTimeMs: Date.parse(q4.expiresAt) + 60_000 });
    ledger.push({ kind: "deposit", yocto: BigInt(q4.amountYocto) });
    const late = await mcp.call("run_noodle", { ...args4, _payment_id: q4.paymentId, _payment_tx: tx4, _payment_sender: PAYER });
    agentSees(late);
    expect(late.isError && late.structuredContent.receipt.outcome === "late_payment" && late.structuredContent.receipt.refund.yocto === q4.amountYocto, "late payment: nothing runs, everything is refunded");
    ledger.push({ kind: "refund", yocto: BigInt(q4.amountYocto) });

    step("13. A run that fails after payment");
    const args5 = { graph: WORKED_GRAPH, inputs: { Idea: "FAIL on purpose" } };
    const q5 = (await mcp.call("run_noodle", args5)).structuredContent.payment;
    const tx5 = chain.transfer(PAYER, MERCHANT, BigInt(q5.amountYocto));
    ledger.push({ kind: "deposit", yocto: BigInt(q5.amountYocto) });
    const failed = await mcp.call("run_noodle", { ...args5, _payment_id: q5.paymentId, _payment_tx: tx5, _payment_sender: PAYER });
    agentSees(failed);
    expect(failed.isError && failed.structuredContent.receipt.outcome === "run_failed" && failed.structuredContent.receipt.refund.yocto === q5.amountYocto, "failed run: the whole deposit is refunded");
    ledger.push({ kind: "refund", yocto: BigInt(q5.amountYocto) });

    step("14. Kill the server between payment verification and settlement (mid-run), then restart");
    const args6 = { graph: WORKED_GRAPH, inputs: { Idea: "HOLD — the model never answers" } };
    const q6 = (await mcp.call("run_noodle", args6)).structuredContent.payment;
    const tx6 = chain.transfer(PAYER, MERCHANT, BigInt(q6.amountYocto));
    ledger.push({ kind: "deposit", yocto: BigInt(q6.amountYocto) });
    mcp.call("run_noodle", { ...args6, _payment_id: q6.paymentId, _payment_tx: tx6, _payment_sender: PAYER }).catch(() => {});
    for (let i = 0; i < 400 && (await stateQuote(q6.paymentId)).status !== "running"; i++) await sleep(10);
    expect((await stateQuote(q6.paymentId)).status === "running", "the paid run is in flight (status running on disk)");
    await server.kill();
    print("  server killed (SIGKILL) mid-run; restarting on the same --out directory…");
    const runs14 = nano.runs();
    server = await startServer(startOpts);
    const after14 = await mcp.call("run_noodle", { ...args6, _payment_id: q6.paymentId, _payment_tx: tx6, _payment_sender: PAYER });
    agentSees(after14);
    const rc14 = after14.structuredContent.receipt;
    expect(rc14.outcome === "interrupted" && rc14.refund.yocto === q6.amountYocto && rc14.refund.status === "sent", "restart: interrupted, whole deposit refunded");
    expect(nano.runs() === runs14, "restart: the run was never repeated");
    ledger.push({ kind: "refund", yocto: BigInt(q6.amountYocto) });

    step("15. Kill the server between refund intent and broadcast, then restart");
    const args7 = { graph: WORKED_GRAPH, inputs: { Idea: "a quiet harbour" } };
    const q7 = (await mcp.call("run_noodle", args7)).structuredContent.payment;
    const tx7 = chain.transfer(PAYER, MERCHANT, BigInt(q7.amountYocto));
    ledger.push({ kind: "deposit", yocto: BigInt(q7.amountYocto) });
    chain.failSendTx = 1_000; // the RPC refuses every broadcast: the refund is signed and recorded, not sent
    const r7 = await mcp.call("run_noodle", { ...args7, _payment_id: q7.paymentId, _payment_tx: tx7, _payment_sender: PAYER });
    agentSees(r7);
    const rc7 = r7.structuredContent.receipt;
    expect(rc7.outcome === "succeeded" && rc7.refund.status === "pending", "the result is delivered with the refund pending");
    const state7 = JSON.parse(await readFile(join(outDir, "near-state.json"), "utf8"));
    const rec7 = Object.values(state7.refunds).find((r) => r.paymentId === q7.paymentId);
    expect(rec7 && rec7.status === "signed" && !!rec7.txHash, "the signed refund and its hash are on disk before any broadcast lands");
    await server.kill();
    chain.failSendTx = 0;
    print("  server killed with the refund signed but not broadcast; RPC healthy again; restarting…");
    server = await startServer(startOpts);
    const replay7 = await mcp.call("run_noodle", { ...args7, _payment_id: q7.paymentId, _payment_tx: tx7, _payment_sender: PAYER });
    agentSees(replay7);
    const rf7 = replay7.structuredContent.receipt.refund;
    expect(rf7.status === "sent" && rf7.txHash === rec7.txHash && chain.txs.has(rec7.txHash), "restart: the same signed refund was broadcast (same hash)");
    ledger.push({ kind: "refund", yocto: BigInt(rf7.yocto) });

    step("16. Balances, reconciled");
    const deposits = ledger.filter((x) => x.kind === "deposit"), refunds = ledger.filter((x) => x.kind === "refund");
    const sum = (xs) => xs.reduce((s, x) => s + x.yocto, 0n);
    const charged = sum(deposits) - sum(refunds);
    const merchantDelta = chain.balance(MERCHANT) - start0.merchant;
    const payerDelta = start0.payer - chain.balance(PAYER);
    const refundTxs = refunds.length;
    print(`  payer    ${formatYoctoAsNear(start0.payer)} → ${formatYoctoAsNear(chain.balance(PAYER))} NEAR`);
    print(`  merchant ${formatYoctoAsNear(start0.merchant)} → ${formatYoctoAsNear(chain.balance(MERCHANT))} NEAR`);
    print(`  ${deposits.length} payments in, ${refunds.length} refunds out; deposits − refunds = ${formatYoctoAsNear(charged)} NEAR charged`);
    print(`  gas: each transaction burns ${formatYoctoAsNear(GAS_YOCTO)} NEAR from its signer`);
    expect(charged === 2n * DOC.charged, `everything charged = the two successful runs (2 × ${formatYoctoAsNear(DOC.charged)} NEAR)`);
    expect(merchantDelta === charged - BigInt(refundTxs) * GAS_YOCTO, "merchant gained exactly the charges, minus its refund gas");
    expect(payerDelta === charged + BigInt(deposits.length) * GAS_YOCTO, "payer lost exactly the charges, plus its transfer gas");
    const payerRefundTxs = [...chain.txs.values()].filter((t) => t.transaction.signer_id === MERCHANT && t.transaction.receiver_id === PAYER).length;
    expect(payerRefundTxs === refundTxs, `exactly ${refundTxs} refund transfers on chain — nothing refunded twice`);
    facts.charged = charged;
  } catch (e) {
    failures.push(`unexpected error: ${e.stack || e}`);
    print(`  ✗ unexpected error: ${e.stack || e}`);
    if (server) print("  server stderr:\n" + server.stderr);
  } finally {
    if (server && server.child.exitCode === null) await server.kill();
    await chain.close();
    await nano.close();
  }

  print(`\n${failures.length ? `FAIL: ${failures.length} of ${checks} checks failed` : `PASS: all ${checks} checks passed`}`);
  return { failures, checks, facts };
}

if (import.meta.url === pathToFileURL(process.argv[1] || "").href) {
  runSimulation().then(({ failures }) => process.exit(failures.length ? 1 : 0), (e) => { console.error(e); process.exit(1); });
}
