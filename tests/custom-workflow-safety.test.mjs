test("input caps: key count, one value, total, and non-string values", () => {
  const g = graph([{ id: "t", type: "text", name: "Idea", fields: { text: "" } }]);
  const many = Object.fromEntries(Array.from({ length: DEFAULT_LIMITS.maxInputKeys + 1 }, (_, i) => ["k" + i, "v"]));
  assert.deepEqual(codes(checkGraphSafety(g, { inputs: many })), ["INPUTS_TOO_LARGE"]);
  assert.deepEqual(codes(checkGraphSafety(g, { inputs: { Idea: "x".repeat(DEFAULT_LIMITS.maxInputChars + 1) } })), ["INPUTS_TOO_LARGE"]);
  const total = { a: "x".repeat(19_000), b: "x".repeat(19_000), c: "x".repeat(19_000) };
  const rt = checkGraphSafety(g, { inputs: total });
  assert.deepEqual(codes(rt), ["INPUTS_TOO_LARGE"]);
  assert.match(rt.refusals[0].message, /total 57000 characters/);
  const ns = checkGraphSafety(g, { inputs: { Idea: 5 } });
  assert.deepEqual(codes(ns), ["INPUTS_TOO_LARGE"]);
  assert.match(ns.refusals[0].message, /input "Idea" must be a string \(got number\)/);
  assert.equal(checkGraphSafety(g, { inputs: { Idea: "fine" } }).ok, true);
});

test("several problems are all reported at once", () => {
  const nodes = [
    { id: "u", type: "upload", fields: {} },
    { id: "x", type: "draw", fields: {} },
    { id: "ep", type: "endpoint", fields: { url: "http://127.0.0.1:8080/" } },
    { id: "t", type: "text", fields: { text: "x" } },
    { id: "e", type: "edit", fields: { ...IMG, prompt: "p" } },
    { id: "l", type: "llm", fields: { model: "m", system: "file:///etc/hosts" } },
  ];
  const r = checkGraphSafety(graph(nodes, [link("1", "t", "text", "e", "image"), link("2", "t", "text", "l", "maxTokens")]),
    { inputs: { a: 1 } });
  const got = new Set(codes(r));
  for (const c of ["NODE_NOT_ALLOWED", "UNKNOWN_NODE", "UNSAFE_WIRING", "UNSAFE_FIELD", "INPUTS_TOO_LARGE"]) assert.ok(got.has(c), c);
  assert.equal(r.refusals.filter((x) => x.code === "NODE_NOT_ALLOWED").length, 2);
  assert.equal(r.refusals.filter((x) => x.code === "UNSAFE_WIRING").length, 2);
  // the endpoint's URL field is reported too
  assert.ok(r.refusals.some((x) => x.code === "UNSAFE_FIELD" && x.nodeId === "ep"));
  assert.throws(() => assertGraphSafe(graph(nodes)), (e) => {
    assert.ok(e instanceof GraphRefusedError);
    assert.equal(e.name, "GraphRefusedError");
    assert.equal(e.mcpCode, undefined);
    assert.ok(e.refusals.length >= 3);
    assert.equal(e.message, e.refusals.map((x) => x.message).join("; "));
    return true;
  });
});

