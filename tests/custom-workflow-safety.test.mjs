test("a share link that inflates past maxGraphBytes is refused before it is decoded (no zip bomb)", async () => {
  const json = '{"nodes":[],"links":[],"pad":"' + " ".repeat(50 * 1024 * 1024) + '"}';
  const url = "https://nanoodle.com/#g=" + gzipSync(Buffer.from(json), { level: 9 }).toString("base64url");
  const before = process.memoryUsage().rss;
  const t0 = Date.now();
  await assert.rejects(readGraphArgs({ url }, { allowShortLinks: false, limits: DEFAULT_LIMITS }), (e) => {
    assert.ok(e instanceof GraphRefusedError);
    assert.equal(e.refusals[0].code, "GRAPH_TOO_LARGE");
    return true;
  });
  assert.ok(Date.now() - t0 < 1000, "bounded inflate is fast");
  assert.ok(process.memoryUsage().rss - before < 40 * 1024 * 1024, "nothing near 50 MB was allocated");
  // an over-long link and an over-long graph string are refused by length
  await assert.rejects(readGraphArgs({ url: "https://nanoodle.com/#j=" + "A".repeat(DEFAULT_LIMITS.maxGraphBytes * 2 + 10) }, { limits: DEFAULT_LIMITS }), { name: "GraphRefusedError" });
  await assert.rejects(readGraphArgs({ graph: " ".repeat(DEFAULT_LIMITS.maxGraphBytes + 1) }, { limits: DEFAULT_LIMITS }), { name: "GraphRefusedError" });
  // a normal link still decodes
  const small = "https://nanoodle.com/#g=" + gzipSync(Buffer.from(JSON.stringify(graph([{ id: "t", type: "text", fields: { text: "hi" } }])))).toString("base64url");
  const ok = await readGraphArgs({ url: small }, { allowShortLinks: false, limits: DEFAULT_LIMITS });
  assert.equal(ok.graph.nodes[0].id, "t");
});

