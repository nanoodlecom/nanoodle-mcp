// Safety rules for caller-supplied workflow graphs on a paid server:
// node allowlist, typed wiring, field values, caps and argument parsing.
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { NODE_TYPES } from "nanoodle";
import {
  NODE_POLICY, DEFAULT_LIMITS, GraphArgsError, GraphRefusedError,
  readGraphArgs, checkGraphSafety, assertGraphSafe, applyInputs,
} from "../src/custom-workflow.mjs";

const link = (id, from, fromPort, to, toPort) => ({ id, from: { node: from, port: fromPort }, to: { node: to, port: toPort } });
const graph = (nodes, links = []) => ({ v: 1, nodes, links });
const codes = (r) => r.refusals.map((x) => x.code);

const IMG = { model: "blackforestlabs/flux-3/klein/text-to-image", size: "1024x1024" };

test("NODE_POLICY covers every engine node type, and nothing else", () => {
  assert.deepEqual(Object.keys(NODE_POLICY).sort(), Object.keys(NODE_TYPES).sort());
  assert.equal(Object.keys(NODE_POLICY).length, 31);
  for (const [type, p] of Object.entries(NODE_POLICY)) {
    assert.equal(typeof p.allowed, "boolean", type);
    assert.ok(p.why && p.why.length > 5, type);
  }
});

test("the allowlist matches the documented table", () => {
  const allowed = Object.keys(NODE_POLICY).filter((t) => NODE_POLICY[t].allowed).sort();
  assert.deepEqual(allowed, ["choice", "comment", "decide", "edit", "image", "ivideo", "join", "llm",
    "model3d", "music", "text", "tts", "tvideo"]);
});

// vision sends no output limit; vedit/remix/transcribe/cleanvoice bill by input media length.
const REFUSED = ["upload", "aupload", "vupload", "mupload", "inpaint", "lipsync", "resize", "vframes", "combine",
  "soundtrack", "trim", "extractaudio", "endpoint", "vision", "vedit", "remix", "transcribe", "cleanvoice"];

for (const type of REFUSED) {
  test(`a ${type} node is refused with NODE_NOT_ALLOWED, naming the node and why`, () => {
    const r = checkGraphSafety(graph([{ id: "a", type, name: "My " + type, fields: {} }]));
    assert.equal(r.ok, false);
    const hit = r.refusals.find((x) => x.code === "NODE_NOT_ALLOWED");
    assert.ok(hit, JSON.stringify(r.refusals));
    assert.equal(hit.nodeId, "a");
    assert.equal(hit.type, type);
    assert.match(hit.message, new RegExp(`node "My ${type}" \\(${type}\\) is not allowed on a paid server`));
    assert.ok(hit.message.includes(NODE_POLICY[type].why.replace(/\.$/, "")), hit.message);
  });
}

